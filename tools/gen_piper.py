"""
Pre-generate every NPC voice line with the Piper "Mihai" Romanian voice (rhasspy/piper-voices ro_RO-mihai-medium, CC0).
Reads the lines straight from the game's JS (so they stay in sync), writes assets/voice/all/<nnn>.ogg and
assets/voice/voices.js (window.NPC_VOICES.all = {spoken text: file}). lst_speak() plays these instead of speechSynthesis,
shifting pitch per character (playbackRate) so NPCs don't all sound identical.

  python tools/gen_piper.py --model <path to ro_RO-mihai-medium.onnx>     (needs: pip install piper-tts soundfile numpy)
Rerun after adding or changing NPC lines in the JS.
"""
import argparse, json, os, re, sys, shutil
import numpy as np, soundfile as sf
from piper import PiperVoice, SynthesisConfig

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "voice")


def js(name):
    return open(os.path.join(ROOT, "js", name), encoding="utf8").read()


def arr(src, name):
    """strings of `const NAME=[...]` (first element of each pair for [['text',w],...])"""
    m = re.search(r"const %s=(\[.*?\]);" % name, src)
    assert m, name
    return [t for t in re.findall(r"\[?'((?:[^'\\]|\\.)*)'", m.group(1))]


def lines():
    st, bt, ap = js("linella_store.js"), js("bemol_terrace.js"), js("airport.js")
    L = []
    # Linella: checkout chatter, one-off cashier/guard lines, street chase (paznic)
    L += arr(st, "ST_LINES") + ["Casă liberă!", "Nu ajung banii...", "Mulțumim! Pachet vă trebuie?", "Paza!! Hoțul!", "Stai! Dă încoace!"]
    L += arr(st, "LST_ION_LINES") + ["Te-am prins! Dă banii!"]
    # Bemol terrace belot table (bemol_talk speaks '-10' as 'minus zece')
    L += [p.replace("-10", "minus zece") for p in arr(bt, "BEMOL_PHRASES")] + arr(bt, "BEMOL_INVITE")
    L += ["Bravo! Eu dau.", "Hai, naciala!", "Tăiem?", "Unde fugi?! Abia am început!", "Na, s-a speriat.", "Lasă, data viitoare.",
          "Oo, bizon! Încă o partidă?", "Hai, revanșa!"]
    # Airport announcements (same templates as airport.js)
    m = re.search(r"const APT_FLIGHTS=(\[.*?\]);", ap); flights = json.loads(m.group(1).replace("'", '"'))
    for _, dest, code, gate in flights:
        d = dest[0] + dest[1:].lower()
        L += [f"Atenție! Pasagerii zborului {code} spre {d} sunt rugați să se prezinte la poarta {gate} pentru îmbarcare.",
              f"Check-in-ul pentru zborul {code} spre {d} se închide în 20 de minute."]
    L += ["Vă rugăm să nu lăsați bagajele nesupravegheate."]
    # Car care (garage mechanics, Bemol pump) and phone missions (callers)
    cc, ph = js("carcare.js"), js("phone.js")
    for n in ["CC_MECH_HI", "CC_MECH_DONE", "CC_MECH_OK", "CC_MECH_BROKE", "CC_PUMP"]: L += arr(cc, n)
    S = r"'((?:[^'\\]|\\.)*)'"
    lf = js("life.js")  # street life: every LF_L_* array
    for n in re.findall(r"const (LF_L_\w+)=", lf): L += arr(lf, n)
    L += re.findall(r"intro_say\('[^']*'," + S, js("intro.js"))
    for pat in [r"sms:" + S, r"ph_say\('[^']*'," + S, r"ph_done\(m,[\w.]+," + S, r"ph_fail\(m," + S]: L += re.findall(pat, ph)
    seen = set(); return [t for t in L if re.search(r"[A-Za-zăâîșțĂÂÎȘȚ]", t) and not (t in seen or seen.add(t))]


def speakable(t):
    """help the phonemizer: spell flight codes and English words the way a Moldovan announcer says them"""
    t = re.sub(r"\bGT (\d)(\d)(\d)\b", r"ge te \1 \2 \3", t)
    return t.replace("Check-in-ul", "Cec-inul")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(); ap.add_argument("--model", required=True); ap.add_argument("--speed", type=float, default=0.92)  # <1 = faster
    a = ap.parse_args()
    v = PiperVoice.load(a.model); sr = v.config.sample_rate
    shutil.rmtree(os.path.join(OUT, "all"), ignore_errors=True); os.makedirs(os.path.join(OUT, "all"))
    files = {}
    for i, text in enumerate(lines()):
        w = np.concatenate([np.frombuffer(c.audio_int16_bytes, np.int16) for c in v.synthesize(speakable(text), SynthesisConfig(length_scale=a.speed))]).astype(np.float32) / 32768
        idx = np.where(np.abs(w) > np.abs(w).max() * .02)[0]
        if len(idx): w = w[max(0, idx[0] - int(.03 * sr)): idx[-1] + int(.1 * sr)]
        w = w / (np.abs(w).max() + 1e-9) * .89
        rel = f"assets/voice/all/{i:03d}.ogg"
        sf.write(os.path.join(ROOT, rel), w, sr, format="OGG", subtype="VORBIS"); files[text] = rel
        print(f"  {rel}  {len(w) / sr:5.2f}s  {text}")
    with open(os.path.join(OUT, "voices.js"), "w", encoding="utf8", newline="\n") as f:
        f.write("// generated by tools/gen_piper.py (Piper ro_RO-mihai-medium, CC0): spoken text -> pre-rendered NPC line\n")
        f.write("window.NPC_VOICES=" + json.dumps({"all": files}, ensure_ascii=False, indent=1) + ";\n")
    print(len(files), "lines -> assets/voice/voices.js")


if __name__ == "__main__":
    main()
